    // Calculate PS for a given type (pure math, no DOM writes)
    function calcPSForType(type) {
        const dimX = parseFloat(val('ps-dim-x')) || 0;
        const dimY = parseFloat(val('ps-dim-y')) || 0;
        const depth = parseFloat(val('ps-depth')) || 0;
        const cover = parseFloat(val('ps-cover')) || 0;
        const fc = parseFloat(val('ps-fc')) || 0;
        const fcp = parseFloat(val('ps-fcp')) || 0;
        const reduction = Math.abs(parseFloat(val('ps-reduction')) || 0);
        const v = parseFloat(val('ps-v')) || 0;
        const mx = parseFloat(val('ps-mx')) || 0;
        const my = parseFloat(val('ps-my')) || 0;
        const bar3 = parseFloat(val('ps-bar-3')) || 0;
        const bar4 = parseFloat(val('ps-bar-4')) || 0;

        const do_eff = depth - cover - Math.max(bar3, bar4);
        let u = 0, ax = 0, ay = 0;

        if (type === 'internal') {
            u = 2 * (dimX + dimY) + Math.PI * do_eff;
            ax = dimX + do_eff;
            ay = dimY + do_eff;
        } else if (type === 'edge') {
            u = 2 * dimX + dimY + (Math.PI / 2) * do_eff;
            ax = dimX + do_eff;
            ay = dimY + do_eff / 2;
        } else {
            u = dimX + dimY + (Math.PI / 4) * do_eff;
            ax = dimX + do_eff / 2;
            ay = dimY + do_eff / 2;
        }
        u = Math.max(0, u - reduction);

        const fcv = 0.17 * Math.sqrt(fc) + 0.3 * fcp;
        const phi = 0.75;
        const fVuo = phi * fcv * u * do_eff / 1000;
        const fVumax = 0.2 * fc * u * do_eff / 1000 * phi;

        let m_factor = 1;
        if (v > 0 && do_eff > 0) {
            if (type === 'internal') {
                m_factor = 1 + (u * mx * 1000) / (8 * v * ax * do_eff) + (u * my * 1000) / (8 * v * ay * do_eff);
            } else if (type === 'edge') {
                m_factor = 1 + (u * mx * 1000) / (8 * v * ax * do_eff) + (u * my * 1000) / (2 * v * ay * do_eff);
            } else {
                m_factor = 1 + (u * mx * 1000) / (2 * v * ax * do_eff) + (u * my * 1000) / (2 * v * ay * do_eff);
            }
        }
        if (!isFinite(m_factor) || m_factor < 1) m_factor = 1;
        const fVu = v * m_factor;

        let status = 'OK', statusDesc = 'No shear reinforcement required';
        if (fVu > fVumax) { status = 'FAIL'; statusDesc = 'Exceeds maximum allowable capacity'; }
        else if (fVu > fVuo) { status = 'REO REQ'; statusDesc = 'Shear reinforcement is required'; }

        return { do_eff, u, fcv, fVu, fVuo, fVumax, status, statusDesc };
    }

    async function exportPunchingShear() {
        const doc = new jsPDF();
        let y = addHeader(doc, 'Punching Shear Check — AS3600');

        // Shared inputs
        y = addSectionTitle(doc, y, 'Geometry & Properties');
        y = addKeyValueTable(doc, y, [
            ['Column X', num('ps-dim-x', 0), 'mm'],
            ['Column Y', num('ps-dim-y', 0), 'mm'],
            ['Slab D', num('ps-depth', 0), 'mm'],
            ['Cover', num('ps-cover', 0), 'mm'],
            ["f'c", num('ps-fc', 0), 'MPa'],
            ['fcp', num('ps-fcp', 1), 'MPa'],
            ['Perim. Reduc.', num('ps-reduction', 0), 'mm'],
        ]);

        y = addSectionTitle(doc, y, 'Loads & Reinforcement');
        y = addKeyValueTable(doc, y, [
            ['V* (kN)', num('ps-v', 0), 'kN'],
            ['M*x (kNm)', num('ps-mx', 0), 'kNm'],
            ['M*y (kNm)', num('ps-my', 0), 'kNm'],
            ['3rd Bar Ø', num('ps-bar-3', 0), 'mm'],
            ['4th Bar Ø', num('ps-bar-4', 0), 'mm'],
        ]);

        // ── 3 Column Types ──
        const types = [
            { id: 'internal', label: 'Internal Column' },
            { id: 'edge',     label: 'Edge Column' },
            { id: 'corner',   label: 'Corner Column' },
        ];

        for (const colType of types) {
            // Check page space — add new page if < 110 remaining
            const pageH = doc.internal.pageSize.getHeight();
            if (y > pageH - 110) {
                doc.addPage();
                y = addHeader(doc, 'Punching Shear Check — AS3600');
            }

            y = addSectionTitle(doc, y, `── ${colType.label} ──`);

            // SVG Diagram
            const svgStr = getPSDiagramSVG(colType.id);
            const imgData = await svgToImage(svgStr, 300, 220);
            if (imgData) {
                const imgW = 65;
                const imgH = imgW * (220 / 300);
                doc.addImage(imgData, 'PNG', 14, y, imgW, imgH);

                // Results table alongside diagram
                const r = calcPSForType(colType.id);
                doc.autoTable({
                    startY: y,
                    margin: { left: 85, right: 14 },
                    head: [['Parameter', 'Value']],
                    body: [
                        ['Effective Depth (do)', `${Math.max(0, r.do_eff).toFixed(0)} mm`],
                        ['Critical Perimeter (u)', `${Math.max(0, r.u).toFixed(0)} mm`],
                        ['Shear Strength (fcv)', `${r.fcv.toFixed(2)} MPa`],
                        ['Design Load (fVu)', `${r.fVu.toFixed(0)} kN`],
                        ['Capacity (fVuo)', `${r.fVuo.toFixed(0)} kN`],
                        ['Max Capacity (fVumax)', `${r.fVumax.toFixed(0)} kN`],
                        ['STATUS', r.status],
                    ],
                    theme: 'grid',
                    styles: { fontSize: 8, cellPadding: 2.5, lineColor: [220, 220, 220], lineWidth: 0.3 },
                    headStyles: { fillColor: BRAND.primary, textColor: BRAND.white, fontStyle: 'bold', fontSize: 8 },
                    columnStyles: {
                        0: { fontStyle: 'bold', cellWidth: 50 },
                        1: { halign: 'right', textColor: BRAND.accent },
                    },
                    didParseCell: function(data) {
                        if (data.section === 'body' && data.row.index === 6) {
                            const text = data.cell.raw || '';
                            if (text === 'FAIL') {
                                data.cell.styles.textColor = [220, 38, 38];
                                data.cell.styles.fillColor = [254, 226, 226];
                                data.cell.styles.fontStyle = 'bold';
                            } else if (text === 'REO REQ') {
                                data.cell.styles.textColor = [217, 119, 6];
                                data.cell.styles.fillColor = [255, 251, 235];
                                data.cell.styles.fontStyle = 'bold';
                            } else if (text === 'OK') {
                                data.cell.styles.textColor = [21, 128, 61];
                                data.cell.styles.fillColor = [220, 252, 231];
                                data.cell.styles.fontStyle = 'bold';
                            }
                            if (data.column.index === 0 && text === 'STATUS') {
                                data.cell.styles.fontStyle = 'bold';
                            }
                        }
                    },
                });
                y = Math.max(y + imgH, doc.lastAutoTable.finalY) + 8;
            }
        }

        addFooter(doc);
        doc.save('Punching_Shear_Check.pdf');
    }

