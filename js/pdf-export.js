    function getResultText(id) {
        const el = document.getElementById(id);
        if (!el) return '0.00';
        // Remove unit span, keep just the number
        const clone = el.cloneNode(true);
        const unit = clone.querySelector('.calc-result-unit');
        if (unit) unit.remove();
        return clone.textContent.trim();
    }

    function getCleanValue(el) {
        const clone = el.cloneNode(true);
        const unit = clone.querySelector('.calc-result-unit');
        if (unit) unit.remove();
        return clone.textContent.trim();
    }

